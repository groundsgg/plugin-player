/**
 * The menu's half of the grounds-global PackSet: the fonts [MenuFonts] names, the sprites [MenuArt]
 * places, and the vanilla `gui` shaders that hide a dialog body's focus outline. Generated here and
 * copied into groundsgg/resourcepacks; `MenuPackTest` writes it to `build/menu-pack/`.
 *
 * Every path sits under `assets/grounds/.../menu/` except the two shaders, which the PackSet has to
 * claim as vanilla overrides.
 */
internal object MenuPack {
    private val gson = GsonBuilder().setPrettyPrinting().disableHtmlEscaping().create()

    fun files(): Map<String, ByteArray> = buildMap {
        put("assets/grounds/font/menu/space.json", spaceFontJson().toByteArray())
        for (dy in 0 until MenuFonts.LINE_HEIGHT) {
            put("assets/grounds/font/menu/text_$dy.json", textFontJson(dy).toByteArray())
        }
        put("assets/grounds/font/menu/art.json", artFontJson().toByteArray())
        put("assets/grounds/font/menu/title.json", titleFontJson().toByteArray())
        for (sprite in MenuArt.sprites) put(texturePath(sprite), png(image(sprite)))
        for (shader in listOf("gui.vsh", "gui.fsh")) {
            val path = "assets/minecraft/shaders/core/$shader"
            val stream =
                MenuPack::class.java.getResourceAsStream("/menu-pack/$path")
                    ?: error("missing test resource menu-pack/$path")
            put(path, stream.use { it.readAllBytes() })
        }
    }

    /** `codepoint advance` per line, hex codepoint, over [MenuFonts.LABEL_RANGE]. */
    fun advancesTable(): String = buildString {
        append("# Generated by MenuPackTest from the 26.3 client jar. Do not edit.\n")
        for (cp in MenuFonts.LABEL_RANGE) {
            VanillaFonts.advance(cp)?.let { append("%04x %d\n".format(cp, it)) }
        }
    }

    /** Like [advancesTable], for [MenuFonts.TITLE]: printable ASCII only. */
    fun titleAdvancesTable(): String = buildString {
        append("# Generated by MenuPackTest from the 26.3 client jar. Do not edit.\n")
        val advances = VanillaFonts.advancesAt(asciiProvider, TITLE_HEIGHT)
        append("%04x %d\n".format(' '.code, TITLE_SPACE))
        for (cp in TITLE_RANGE) advances[cp]?.let { append("%04x %d\n".format(cp, it)) }
    }

    private const val TITLE_HEIGHT = 16
    private const val TITLE_SPACE = 8
    private val TITLE_RANGE = 0x21..0x7E

    private val asciiProvider: VanillaFonts.Provider
        get() = VanillaFonts.providers.single { it.file == "minecraft:font/ascii.png" }

    /**
     * Vanilla's ASCII sheet at [TITLE_HEIGHT] px: twice its 8 px cells, so every glyph is drawn
     * twice the size with the same shapes. The ascent stays 7, which puts the glyph's top on the
     * line's top. A space provider gives the blank its doubled width too.
     */
    private fun titleFontJson(): String =
        providers(
            listOf(
                JsonObject().apply {
                    addProperty("type", "space")
                    add("advances", JsonObject().apply { addProperty(" ", TITLE_SPACE) })
                },
                JsonObject().apply {
                    addProperty("type", "bitmap")
                    addProperty("file", asciiProvider.file)
                    addProperty("ascent", 7)
                    addProperty("height", TITLE_HEIGHT)
                    add(
                        "chars",
                        JsonArray().apply {
                            asciiProvider.chars.forEach { row ->
                                add(
                                    buildString {
                                        row.codePoints().forEach { cp ->
                                            if (cp in TITLE_RANGE) appendCodePoint(cp)
                                            else append('\u0000')
                                        }
                                    }
                                )
                            }
                        },
                    )
                },
            )
        )

    fun texturePath(sprite: MenuSprite) = "assets/grounds/textures/font/menu/${sprite.name}.png"

    private fun spaceFontJson(): String {
        val advances = JsonObject()
        for (bit in MenuFonts.powers) {
            advances.addProperty(MenuFonts.negChar(bit).toString(), -(1 shl bit))
            advances.addProperty(MenuFonts.posChar(bit).toString(), 1 shl bit)
        }
        return providers(
            listOf(
                JsonObject().apply {
                    addProperty("type", "space")
                    add("advances", advances)
                }
            )
        )
    }

    /**
     * Vanilla's default font (space + every bitmap provider of `minecraft:include/default`, in
     * vanilla's order) with each ascent lowered by [dy]. Grids keep only [MenuFonts.LABEL_RANGE]
     * (the rest becomes U+0000, which the client skips), which keeps the nine copies small while
     * every label glyph still resolves to the provider vanilla would pick.
     */
    private fun textFontJson(dy: Int): String =
        providers(
            listOf(
                JsonObject().apply {
                    addProperty("type", "reference")
                    addProperty("id", "minecraft:include/space")
                }
            ) +
                VanillaFonts.providers
                    .map { p -> p to p.chars.map(::keepLabelRange) }
                    .filter { (_, rows) -> rows.any { row -> row.any { it != '\u0000' } } }
                    .map { (p, rows) ->
                        JsonObject().apply {
                            addProperty("type", "bitmap")
                            addProperty("file", p.file)
                            addProperty("ascent", p.ascent - dy)
                            addProperty("height", p.height)
                            add("chars", JsonArray().apply { rows.forEach(::add) })
                        }
                    }
        )

    private fun keepLabelRange(row: String): String = buildString {
        row.codePoints().forEach { cp ->
            if (cp in MenuFonts.LABEL_RANGE) appendCodePoint(cp) else append('\u0000')
        }
    }

    private fun artFontJson(): String =
        providers(
            MenuArt.sprites.flatMap { sprite ->
                (0 until MenuFonts.LINE_HEIGHT).map { dy ->
                    JsonObject().apply {
                        addProperty("type", "bitmap")
                        addProperty("file", "grounds:font/menu/${sprite.name}.png")
                        addProperty("ascent", 7 - dy)
                        addProperty("height", sprite.height)
                        add("chars", JsonArray().apply { add(sprite.glyph(dy).toString()) })
                    }
                }
            }
        )

    private fun providers(providers: List<JsonObject>): String =
        gson.toJson(
            JsonObject().apply { add("providers", JsonArray().apply { providers.forEach(::add) }) }
        )

