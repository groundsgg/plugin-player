    /**
     * The sea behind the map: a slot border, a gradient from light at the top to deep at the
     * bottom, shallows where it touches land, and the land's shadow one pixel down and right.
     */
    private fun deepSea(g: Graphics2D, w: Int, h: Int) {
        inset(g, w, h)
        val land = { x: Int, y: Int ->
            y in 0 until WorldMap.height && x in 0 until WorldMap.WIDTH && WorldMap.at(x, y) != null
        }
        val bands = 8
        for (y in 0 until WorldMap.height) {
            val t = (y * bands / WorldMap.height).toDouble() / (bands - 1)
            val base = mix(SEA_TOP, SEA_BOTTOM, t)
            for (x in 0 until WorldMap.WIDTH) {
                if (land(x, y)) continue
                g.color =
                    when {
                        land(x - 1, y - 1) -> SEA_SHADOW
                        land(x - 1, y) || land(x + 1, y) || land(x, y - 1) || land(x, y + 1) ->
                            SHALLOW
                        else -> base
                    }
                g.fillRect(x + 1, y + 1, 1, 1)
            }
        }
    }

    private fun mix(a: Color, b: Color, t: Double) =
        Color(
            (a.red + (b.red - a.red) * t).toInt(),
            (a.green + (b.green - a.green) * t).toInt(),
            (a.blue + (b.blue - a.blue) * t).toInt(),
        )

    /**
     * [continent]'s land in its colours: lit where the coast faces up or left, shaded where it
     * faces down or right. [picked] draws it in gold with a white 1 px ring around it, the sprite
     * one px larger per side. (The palette is looked up when drawing: these drawings are built
     * before the colours below are initialised.)
     */
    private fun shadedLand(continent: WorldMap.Continent, picked: Boolean) =
        { g: Graphics2D, _: Int, _: Int ->
            val palette = if (picked) GOLD_PALETTE else PALETTES.getValue(continent)
            val outline = picked
            val b = WorldMap.bounds(continent)
            val pad = if (outline) 1 else 0
            val mine = { x: Int, y: Int ->
                y in 0 until WorldMap.height &&
                    x in 0 until WorldMap.WIDTH &&
                    WorldMap.at(x, y) == continent
            }
            for (y in b.y - pad until b.y + b.h + pad) {
                for (x in b.x - pad until b.x + b.w + pad) {
                    val colour =
                        when {
                            mine(x, y) ->
                                when {
                                    !mine(x - 1, y) || !mine(x, y - 1) -> palette.light
                                    !mine(x + 1, y) || !mine(x, y + 1) -> palette.dark
                                    else -> palette.face
                                }
                            outline &&
                                (-1..1).any { dy -> (-1..1).any { dx -> mine(x + dx, y + dy) } } ->
                                LIGHT
                            else -> null
                        } ?: continue
                    g.color = colour
                    g.fillRect(x - b.x + pad, y - b.y + pad, 1, 1)
                }
            }
        }

    /** [continent]'s hover-card silhouette ([WorldMap.cardPixel]), shaded like the map. */
    private fun card(continent: WorldMap.Continent) = { g: Graphics2D, w: Int, h: Int ->
        val palette = PALETTES.getValue(continent)
        val mine = { x: Int, y: Int ->
            x in 0 until w && y in 0 until h && WorldMap.cardPixel(continent, x, y)
        }
        for (y in 0 until h) {
            for (x in 0 until w) {
                if (!mine(x, y)) continue
                g.color =
                    when {
                        !mine(x - 1, y) || !mine(x, y - 1) -> palette.light
                        !mine(x + 1, y) || !mine(x, y + 1) -> palette.dark
                        else -> palette.face
                    }
                g.fillRect(x, y, 1, 1)
            }
        }
    }

    /** Draws [grid] (one char per pixel, `.` transparent) at ([x], [y]) in [colours]. */
    private fun pixels(
        g: Graphics2D,
        x: Int,
        y: Int,
        grid: List<String>,
        colours: Map<Char, Color>,
    ) {
        grid.forEachIndexed { row, line ->
            line.forEachIndexed { col, c ->
                val colour = colours[c] ?: return@forEachIndexed
                g.color = colour
                g.fillRect(x + col, y + row, 1, 1)
            }
        }
    }

