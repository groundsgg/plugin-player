    /**
     * Lobby 2.2.6's /region sprites, drawn exactly as that version shipped them: its panel and sea,
     * and the continents from its 220 px mask. They must not change while a lobby can still use
     * them.
     */
    private fun legacyRegionDrawings(): List<Pair<MenuSprite, (Graphics2D, Int, Int) -> Unit>> {
        val rows =
            MenuPack::class.java.getResourceAsStream("world-map-220.txt")!!.bufferedReader().use {
                it.readLines().filter(String::isNotEmpty)
            }
        val legacy = MenuArt.legacyRegion
        val continents = WorldMap.Continent.entries
        val pickable = continents.filter { it.pickable }
        return listOf<Pair<MenuSprite, (Graphics2D, Int, Int) -> Unit>>(
            legacy[0] to ::window,
            legacy[1] to ::sea,
        ) +
            continents.mapIndexed { i, c -> legacy[2 + i] to land(rows, c, picked = false) } +
            pickable.mapIndexed { i, c -> legacy[8 + i] to land(rows, c, picked = true) }
    }

    /** The sea behind the map: a slot border around [SEA]. */
    private fun sea(g: Graphics2D, w: Int, h: Int) {
        inset(g, w, h)
        g.color = SEA
        g.fillRect(1, 1, w - 2, h - 2)
    }

    /**
     * [continent]'s pixels of a [rows] mask, cropped to their bounds: gold when [picked], green
     * when it can be picked, grey otherwise, with the coast (a pixel next to sea) a shade darker.
     */
    private fun land(rows: List<String>, continent: WorldMap.Continent, picked: Boolean) =
        { g: Graphics2D, _: Int, _: Int ->
            val (face, edge) =
                when {
                    picked -> PICKED to PICKED_EDGE
                    continent.pickable -> LAND to LAND_EDGE
                    else -> IDLE to IDLE_EDGE
                }
            val mine = { x: Int, y: Int ->
                y in rows.indices && x in 0 until rows[y].length && rows[y][x] == continent.mark
            }
            val pixels =
                rows.indices.flatMap { y -> rows[y].indices.filter { mine(it, y) }.map { it to y } }
            val left = pixels.minOf { it.first }
            val top = pixels.minOf { it.second }
            for ((x, y) in pixels) {
                val coast = !mine(x - 1, y) || !mine(x + 1, y) || !mine(x, y - 1) || !mine(x, y + 1)
                g.color = if (coast) edge else face
                g.fillRect(x - left, y - top, 1, 1)
            }
        }

    fun image(sprite: MenuSprite): BufferedImage {
        val draw =
            drawings[sprite]
                ?: if (sprite in MenuArt.hits) ::hitStrip
                else error("no drawing for sprite ${sprite.name}")
        val img = BufferedImage(sprite.width, sprite.height, BufferedImage.TYPE_INT_ARGB)
        val g = img.createGraphics()
        draw(g, sprite.width, sprite.height)
        g.dispose()
        return img
    }

    private fun png(image: BufferedImage): ByteArray =
        ByteArrayOutputStream().also { ImageIO.write(image, "png", it) }.toByteArray()

    /**
     * A vanilla window: black outline with cut corners, white top-left bevel, grey bottom-right.
     */
    private fun window(g: Graphics2D, w: Int, h: Int) {
        g.color = OUTLINE
        g.fillRect(2, 0, w - 4, h)
        g.fillRect(0, 2, w, h - 4)
        g.fillRect(1, 1, w - 2, h - 2)
        g.color = FACE
        g.fillRect(1, 1, w - 2, h - 2)
        g.color = LIGHT
        g.fillRect(1, 1, w - 3, 2)
        g.fillRect(1, 1, 2, h - 3)
        g.color = SHADE
        g.fillRect(3, h - 3, w - 4, 2)
        g.fillRect(w - 3, 3, 2, h - 4)
        g.color = FACE
        g.fillRect(3, 3, w - 6, h - 6)
    }

    /** White at alpha 1/255: invisible, but a pixel the client counts as there. */
    private fun hitStrip(g: Graphics2D, w: Int, h: Int) {
        g.color = Color(255, 255, 255, 1)
        g.fillRect(0, 0, w, h)
    }

    /** An inventory slot strip: dark top-left, white bottom-right. */
    private fun inset(g: Graphics2D, w: Int, h: Int) {
        g.color = SLOT
        g.fillRect(0, 0, w, h)
        g.color = SLOT_DARK
        g.fillRect(0, 0, w - 1, 1)
        g.fillRect(0, 0, 1, h - 1)
        g.color = LIGHT
        g.fillRect(1, h - 1, w - 1, 1)
        g.fillRect(w - 1, 1, 1, h - 1)
    }

    private fun bevel(
        g: Graphics2D,
        w: Int,
        h: Int,
        face: Color,
        light: Color,
        dark: Color,
        xOff: Int = 0,
    ) {
        g.color = OUTLINE
        g.fillRect(xOff, 0, w, h)
        g.color = face
        g.fillRect(xOff + 1, 1, w - 2, h - 2)
        g.color = light
        g.fillRect(xOff + 1, 1, w - 2, 1)
        g.fillRect(xOff + 1, 1, 1, h - 2)
        g.color = dark
        g.fillRect(xOff + 1, h - 2, w - 2, 1)
        g.fillRect(xOff + w - 2, 1, 1, h - 2)
    }

    private fun arrow(g: Graphics2D, left: Boolean) {
        g.color = LIGHT
        for (i in 0 until 4) g.fillRect(if (left) 5 + i else 8 - i, 6 - i, 1, 2 + 2 * i)
    }
